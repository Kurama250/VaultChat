let lang = localStorage.getItem("shard-lang") || (navigator.language.startsWith("fr") ? "fr" : "en");
if (!STRINGS[lang]) lang = "fr";

export function getLang() {
  return lang;
}

export function setLang(next) {
  if (!STRINGS[next]) return;
  lang = next;
  localStorage.setItem("shard-lang", lang);
  document.documentElement.lang = lang;
}

export function t(key, vars = {}) {
  let text = STRINGS[lang][key] || STRINGS.fr[key] || key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value ?? ""));
  }
  return text;
}

export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    const val = t(key);
    if (el.dataset.i18nAttr) {
      el.setAttribute(el.dataset.i18nAttr, val);
    } else if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
      if (el.hasAttribute("placeholder")) el.placeholder = val;
      else el.textContent = val;
    } else {
      el.textContent = val;
    }
  });
}

